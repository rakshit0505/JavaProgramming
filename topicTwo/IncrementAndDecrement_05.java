package topicTwo;

public class IncrementAndDecrement_05 {

    public static void main(String[] args) {
        int a = 10;
        System.out.println("Value before increment and decrement: a = " + a);

        ++a;
        System.out.println("Value after pre-increment: a = " + a);

        a++;
        System.out.println("Value after post-increment: a = " + a);

        --a;
        System.out.println("Value after pre-decrement: a = " + a);

        a--;
        System.out.println("Value after post-decrement: a = " + a);

    }

}
