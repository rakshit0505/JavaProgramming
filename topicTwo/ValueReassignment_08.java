package topicTwo;

public class ValueReassignment_08 {

    public static void main(String[] args) {
        int a = 10;
        System.out.println("Value: " + a);

        a += 5;
        System.out.println("Value: " + a);

        a *= 2;
        System.out.println("Value: " + a);

        a -= 4;
        System.out.println("Value: " + a);
    }

}
