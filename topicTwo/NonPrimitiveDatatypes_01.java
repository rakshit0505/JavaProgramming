package topicTwo;

public class NonPrimitiveDatatypes_01 {

    public static void main(String[] args) {

        int a = 10;
        double b = 50.50;
        char c = 'r';
        boolean d = true;

        System.out.println("The integer value stored is: " + a);
        System.out.println("The double value stored is: " + b);
        System.out.println("The char value stored is: " + c);
        System.out.println("The boolean value stored is: " + d);

    }

}
