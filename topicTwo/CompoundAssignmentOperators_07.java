package topicTwo;

public class CompoundAssignmentOperators_07 {

    public static void main(String[] args) {
        int a = 10;

        a += 5;
        System.out.println("Value for += operation: " + a);

        a -= 5;
        System.out.println("Value for -= operation: " + a);

        a *= 5;
        System.out.println("Value for *= operation: " + a);

        a /= 5;
        System.out.println("Value for /= operation: " + a);

    }

}
